const TRUST_BADGES = [
  { icon: ShieldCheck, label: "100% local & private" },
  { icon: Cpu, label: "Free AI, no account" },
  { icon: WifiOff, label: "Works offline" },
];

interface TemplateInfo {
  file: string;
  name: string;
  description: string;
  icon: LucideIcon;
}

